
# Python Basics

# 1. Printing output
print("Hello, World!")
print("Welcome to Python Programming")

# 2. Variables
name = "Laxmi"
age = 21
course = "BCA"

print("Name:", name)
print("Age:", age)
print("Course:", course)

# 3. Data Types
a = 10
b = 10.5
c = "Python"
d = True

print(type(a))
print(type(b))
print(type(c))
print(type(d))

# 4. Arithmetic Operators
num1 = 20
num2 = 10

print("Addition:", num1 + num2)
print("Subtraction:", num1 - num2)
print("Multiplication:", num1 * num2)
print("Division:", num1 / num2)

# 5. User Input
user_name = input("Enter your name: ")
print("Welcome", user_name)

# 6. Conditional Statements
number = 10

if number > 0:
    print("Positive Number")
else:
    print("Negative Number")

# 7. For Loop
for i in range(1, 6):
    print(i)

# 8. While Loop
i = 1
while i <= 5:
    print(i)
    i += 1
